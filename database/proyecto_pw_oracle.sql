-- 5. VISTAS OBLIGATORIAS (Reportes Empresariales)
CREATE OR REPLACE VIEW V_REPORTES_VENTAS AS
SELECT 
    v.idVenta,
    v.numeroFactura,
    v.fecha,
    c.cedula AS cliente_cedula,
    c.nombres || ' ' || c.apellidos AS cliente_nombre,
    u.usuario AS vendedor,
    v.subtotal,
    v.iva,
    v.total
FROM VENTAS v
INNER JOIN CLIENTES c ON v.idCliente = c.idCliente
INNER JOIN USUARIOS u ON v.idUsuario = u.idUsuario;

-- 6. TRIGGERS OBLIGATORIOS

-- A. Trigger BEFORE INSERT → Validación de datos (ej. formato correo y cédula)
CREATE OR REPLACE TRIGGER TRG_USUARIOS_BI
BEFORE INSERT ON USUARIOS
FOR EACH ROW
BEGIN
    IF :NEW.correo IS NOT NULL AND NOT REGEXP_LIKE(:NEW.correo, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,4}$') THEN
        RAISE_APPLICATION_ERROR(-20002, 'Formato de correo electrónico inválido.');
    END IF;
    IF LENGTH(:NEW.cedula) != 10 THEN
        RAISE_APPLICATION_ERROR(-20003, 'La cédula debe tener exactamente 10 dígitos.');
    END IF;
END;
/

-- B. Trigger AFTER UPDATE → Auditoría de cambios en usuarios
CREATE OR REPLACE TRIGGER TRG_USUARIOS_AU
AFTER UPDATE ON USUARIOS
FOR EACH ROW
BEGIN
    INSERT INTO BITACORA (idUsuario, accion, fecha, ip)
    VALUES (:NEW.idUsuario, 'Actualización de usuario: ' || :OLD.usuario || ' a ' || :NEW.usuario, SYSTIMESTAMP, 'localhost');
END;
/

-- C. Trigger BEFORE DELETE → Restricción por relaciones (no eliminar clientes con ventas)
CREATE OR REPLACE TRIGGER TRG_CLIENTES_BD
BEFORE DELETE ON CLIENTES
FOR EACH ROW
DECLARE
    v_cantidad NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cantidad FROM VENTAS WHERE idCliente = :OLD.idCliente;
    IF v_cantidad > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'No se puede eliminar el cliente porque tiene ventas registradas.');
    END IF;
END;
/

-- D. Trigger AFTER INSERT/UPDATE → Actualización automática de fecha de modificación
CREATE OR REPLACE TRIGGER TRG_USUARIOS_AIU
BEFORE INSERT OR UPDATE ON USUARIOS
FOR EACH ROW
BEGIN
    :NEW.fechaModificacion := SYSTIMESTAMP;
END;
/

-- 7. PROCEDIMIENTOS ALMACENADOS OBLIGATORIOS

-- A. Login de Usuario (15 parámetros)
CREATE OR REPLACE PROCEDURE PRC_LOGIN_USUARIO (
    p_usuario IN VARCHAR2,
    p_idUsuario OUT NUMBER,
    p_password OUT VARCHAR2,
    p_nombres OUT VARCHAR2,
    p_apellidos OUT VARCHAR2,
    p_correo OUT VARCHAR2,
    p_telefono OUT VARCHAR2,
    p_cedula OUT VARCHAR2,
    p_estado OUT VARCHAR2,
    p_intentosFallidos OUT NUMBER,
    p_bloqueadoHasta OUT VARCHAR2,
    p_idRol OUT NUMBER,
    p_rol OUT VARCHAR2,
    p_estaBloqueado OUT NUMBER,
    p_segundosRestantes OUT NUMBER
) AS
BEGIN
    SELECT u.idUsuario, u.password, u.nombres, u.apellidos, u.correo, u.telefono, u.cedula, u.estado, u.intentosFallidos, 
           TO_CHAR(u.bloqueadoHasta, 'YYYY-MM-DD HH24:MI:SS'), u.idRol, r.nombre,
           CASE WHEN u.bloqueadoHasta IS NOT NULL AND u.bloqueadoHasta > SYSTIMESTAMP THEN 1 ELSE 0 END,
           COALESCE(EXTRACT(SECOND FROM (u.bloqueadoHasta - SYSTIMESTAMP)), 0)
    INTO p_idUsuario, p_password, p_nombres, p_apellidos, p_correo, p_telefono, p_cedula, p_estado, p_intentosFallidos,
         p_bloqueadoHasta, p_idRol, p_rol, p_estaBloqueado, p_segundosRestantes
    FROM USUARIOS u
    INNER JOIN ROLES r ON u.idRol = r.idRol
    WHERE u.usuario = p_usuario AND u.estado = 'Activo';
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_idUsuario := NULL;
        p_password := NULL;
        p_nombres := NULL;
        p_apellidos := NULL;
        p_correo := NULL;
        p_telefono := NULL;
        p_cedula := NULL;
        p_estado := NULL;
        p_intentosFallidos := 0;
        p_bloqueadoHasta := NULL;
        p_idRol := NULL;
        p_rol := NULL;
        p_estaBloqueado := 0;
        p_segundosRestantes := 0;
END;
/

-- B. Registro de Usuario (con validación de duplicados)
CREATE OR REPLACE PROCEDURE PRC_REGISTRO_USUARIO (
    p_usuario IN VARCHAR2,
    p_password IN VARCHAR2,
    p_nombres IN VARCHAR2,
    p_apellidos IN VARCHAR2,
    p_correo IN VARCHAR2,
    p_telefono IN VARCHAR2,
    p_cedula IN VARCHAR2,
    p_idRol IN NUMBER,
    p_resultado OUT VARCHAR2
) AS
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM USUARIOS WHERE usuario = p_usuario OR cedula = p_cedula;
    IF v_existe > 0 THEN
        p_resultado := 'ERROR_DUPLICADO';
    ELSE
        INSERT INTO USUARIOS (usuario, password, nombres, apellidos, correo, telefono, cedula, idRol, estado)
        VALUES (p_usuario, p_password, p_nombres, p_apellidos, p_correo, p_telefono, p_cedula, p_idRol, 'Activo');
        p_resultado := 'OK';
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        p_resultado := SQLERRM;
END;
/

-- C. Ventas Totales por Cliente
CREATE OR REPLACE PROCEDURE PRC_VENTAS_TOTALES_CLIENTE (
    p_idCliente IN NUMBER,
    p_total_ventas OUT NUMBER
) AS
BEGIN
    SELECT COALESCE(SUM(total), 0) INTO p_total_ventas 
    FROM VENTAS 
    WHERE idCliente = p_idCliente;
END;
/

-- D. Ventas por Rango de Fechas
CREATE OR REPLACE PROCEDURE PRC_VENTAS_POR_FECHA (
    p_fecha_inicio IN TIMESTAMP,
    p_fecha_fin IN TIMESTAMP,
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
    SELECT * FROM V_REPORTES_VENTAS
    WHERE fecha BETWEEN p_fecha_inicio AND p_fecha_fin
    ORDER BY fecha DESC;
END;
/

-- E. CRUD de Clientes mediante procedimiento (Optimizado para compatibilidad con PDO_OCI)
CREATE OR REPLACE PROCEDURE PRC_CRUD_CLIENTE (
    p_operacion IN VARCHAR2, -- 'C' (Create), 'U' (Update), 'D' (Delete)
    p_idCliente IN OUT NUMBER,
    p_cedula IN VARCHAR2 DEFAULT NULL,
    p_nombres IN VARCHAR2 DEFAULT NULL,
    p_apellidos IN VARCHAR2 DEFAULT NULL,
    p_correo IN VARCHAR2 DEFAULT NULL,
    p_telefono IN VARCHAR2 DEFAULT NULL,
    p_direccion IN VARCHAR2 DEFAULT NULL
) AS
BEGIN
    IF p_operacion = 'C' THEN
        INSERT INTO CLIENTES (cedula, nombres, apellidos, correo, telefono, direccion)
        VALUES (p_cedula, p_nombres, p_apellidos, p_correo, p_telefono, p_direccion)
        RETURNING idCliente INTO p_idCliente;
    ELSIF p_operacion = 'U' THEN
        UPDATE CLIENTES 
        SET cedula = NVL(p_cedula, cedula),
            nombres = NVL(p_nombres, nombres),
            apellidos = NVL(p_apellidos, apellidos),
            correo = NVL(p_correo, correo),
            telefono = NVL(p_telefono, telefono),
            direccion = NVL(p_direccion, direccion)
        WHERE idCliente = p_idCliente;
    ELSIF p_operacion = 'D' THEN
        DELETE FROM CLIENTES WHERE idCliente = p_idCliente;
    END IF;
END;
/


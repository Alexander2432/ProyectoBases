-- 1. ELIMINACIÓN DE TABLAS (Por si se vuelve a ejecutar)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
    'DETALLE_COMPRAS', 'COMPRAS', 'DETALLE_VENTAS', 'VENTAS', 
    'PRODUCTOS', 'CATEGORIAS_IVA', 'CLIENTES', 'BITACORA', 
    'PERMISOS', 'MENUS', 'USUARIOS', 'ROLES'
  )) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/

-- 2. ELIMINACIÓN DE VISTAS Y PROCEDIMIENTOS
BEGIN
  FOR v IN (SELECT view_name FROM user_views WHERE view_name = 'V_REPORTES_VENTAS') LOOP
    EXECUTE IMMEDIATE 'DROP VIEW ' || v.view_name;
  END LOOP;
  FOR p IN (SELECT object_name FROM user_objects WHERE object_type = 'PROCEDURE' AND object_name IN (
    'PRC_LOGIN_USUARIO', 'PRC_REGISTRO_USUARIO', 'PRC_VENTAS_TOTALES_CLIENTE', 
    'PRC_VENTAS_POR_FECHA', 'PRC_CRUD_CLIENTE'
